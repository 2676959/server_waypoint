    /** The advance of every glyph beyond ASCII that the sheets have, by code point. */
    static final Map<Integer, Integer> ADVANCES = decode();

    private ChatFontSheets() {
    }

    private static Map<Integer, Integer> decode() {
        Map<Integer, Integer> advances = new HashMap<>();
        for (String run : RUNS) {
            int space = run.indexOf(' ');
            int codePoint = Integer.parseInt(run, 0, space, 16);
            for (int index = space + 1; index < run.length(); index++) {
                int advance = Character.digit(run.charAt(index), 36);
                if (advance > 0) {
                    advances.put(codePoint, advance);
                }
                codePoint++;
            }
        }
        return Map.copyOf(advances);
    }
